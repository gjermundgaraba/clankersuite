type Families = typeof glyphFamilies;

/** The name of one glyph in the inventory, such as `"caret-down"` or `"bolt"`. */
export type GlyphName = {
  [Family in keyof Families]: keyof Families[Family];
}[keyof Families];

const GRID_SIZE = 12;

/** The rows of a drawing, trimmed: twelve strings of twelve `#` or `.` for a well-drawn glyph. */
export const artRows = (art: string): readonly string[] =>
  pipe(art, String.trim, String.split("\n"), Array.map(String.trim));

const INK_RUN = /#+/gu;

/** A drawing as rectangles one cell tall: one for each horizontal run of ink in each row,
 *  up to `width` cells into the row. */
export const toCells = (art: string, width: number): readonly Cell[] =>
  Array.flatMap(artRows(art), (row, y) =>
    Array.map(
      Array.fromIterable(row.slice(0, width).matchAll(INK_RUN)),
      (run): Cell => [run.index, y, run[0].length, 1]
    )
  );

const drawFamily = <Name extends string>(
  family: Record.ReadonlyRecord<Name, string>
): Record.ReadonlyRecord<Name, readonly Cell[]> =>
  Record.map(family, (art) => toCells(art, GRID_SIZE));

/** Every glyph as the rectangles `Glyph.view` draws. */
